"""Generate or check the Server's pin of the Matrix consumer export (ClearView M1).

    py tools/matrix_pin.py --check                      # the tracked pin is what the pinned publisher exports
    py tools/matrix_pin.py --write --review "<status>"  # re-pin to the Matrix checkout's HEAD

Run from `server/`. The Matrix checkout is found as `check_matrix_contract.py` finds it:
`MUNARIUM_MATRIX_ROOT`, then `munarium-matrix` inside or beside the repository root.

The pin has two generated outputs and no hand-written content:

    contract/matrix-consumer/matrix-consumer.json   the publisher's `--consumer-out`
                                                    export, byte for byte
    src/munarium-core/src/matrix_pin.rs             the constants the Server compiles
                                                    against: wire version, locked bundle
                                                    digest, verified source, publisher
                                                    revision and its review status, the
                                                    export's sha256 and profile digest

Both modes require the Matrix checkout to be a clean `contract/` tree, and `--check`
requires its HEAD to be the pinned publisher revision. They run the publisher's
`--self-test`, cut the wire bundle and `--verify` it, `--check` the vendored v1.4 copy
in `contract/matrix/` against that cut, compare the 17 locked files byte for byte, export
the consumer profile, `--consumer-check` it and recompute its `profile_digest`
independently. Any failure exits 1 and writes nothing. Stdlib only.

The Server's own Rust tests (`munarium-core`'s `matrix_pin` test and
`munarium-api-types`' `matrix_contract` test) verify the tracked pin with no Matrix
checkout; this tool is the step that ties the pin to the publisher.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_matrix_contract import VENDORED, matrix_root  # noqa: E402

SERVER = Path(__file__).resolve().parents[1]
EXPORT = SERVER / "contract" / "matrix-consumer" / "matrix-consumer.json"
PIN_RS = SERVER / "src" / "munarium-core" / "src" / "matrix_pin.rs"
HEX40 = re.compile(r"^[0-9a-f]{40}$")
HEX64 = re.compile(r"^[0-9a-f]{64}$")


class PinError(Exception):
    pass


def git(matrix: Path, *args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=matrix, capture_output=True, text=True, check=True
    ).stdout.strip()


def publisher(matrix: Path, *args: str) -> None:
    script = matrix / "contract" / "publish.py"
    result = subprocess.run([sys.executable, str(script), *args], capture_output=True, text=True)
    if result.returncode != 0:
        raise PinError(f"publish.py {' '.join(args)} failed:\n{result.stdout}{result.stderr}")


def profile_digest(profile: dict) -> str:
    payload = json.dumps(profile, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    return hashlib.sha256(payload.encode()).hexdigest()


def rust_str(value: str) -> str:
    if not re.fullmatch(r"[ -~]*", value) or '"' in value or "\\" in value:
        raise PinError(f"refusing to embed {value!r}: printable ASCII without quotes only")
    return value


def render(values: dict[str, str]) -> str:
    v = {k: rust_str(x) for k, x in values.items()}
    return f"""// SPDX-License-Identifier: Apache-2.0
// @generated by server/tools/matrix_pin.py from the Matrix publisher's consumer
// export. Do not edit; regenerate from `server/` with
// `py tools/matrix_pin.py --write --review "<status>"` and check with `--check`.
//! The Matrix wire contract this Server build consumes (ClearView M1).
//!
//! The values come from `contract/matrix-consumer/matrix-consumer.json`, the
//! publisher's `--consumer-out` export, and replace the compile-time read of
//! `contract/matrix/VERSION`. `tests/matrix_pin.rs` verifies them against that
//! export with no Matrix checkout.

/// The supported wire contract version.
pub const CONTRACT_VERSION: &str = "{v['contract_version']}";

/// The locked digest over the wire bundle's sorted file hashes.
pub const BUNDLE_DIGEST: &str = "{v['bundle_digest']}";

/// The Matrix revision the publisher verified against the released bundle.
pub const VERIFIED_SOURCE_COMMIT: &str = "{v['verified_source_commit']}";

/// The `iokaio/munarium-matrix` publisher revision that produced the export.
pub const PUBLISHER_REVISION: &str = "{v['publisher_revision']}";

/// The review status of [`PUBLISHER_REVISION`] when this pin was generated.
pub const PUBLISHER_REVIEW: &str = "{v['publisher_review']}";

/// SHA-256 of the export file's bytes.
pub const EXPORT_SHA256: &str = "{v['export_sha256']}";

/// The export's `profile_digest`.
pub const PROFILE_DIGEST: &str = "{v['profile_digest']}";
"""


def tracked_values() -> dict[str, str]:
    if not PIN_RS.is_file():
        raise PinError(f"{PIN_RS} is missing; generate it with --write")
    text = PIN_RS.read_text(encoding="utf-8")
    names = {
        "publisher_revision": "PUBLISHER_REVISION",
        "publisher_review": "PUBLISHER_REVIEW",
    }
    out = {}
    for key, const in names.items():
        m = re.search(rf'pub const {const}: &str =\s*"([^"]*)";', text)
        if not m:
            raise PinError(f"{PIN_RS} has no {const}")
        out[key] = m.group(1)
    return out


def build(matrix: Path, review: str) -> tuple[bytes, str]:
    """Run the publisher at the checkout and return the export bytes and the pin source."""
    revision = git(matrix, "rev-parse", "HEAD")
    if not HEX40.match(revision):
        raise PinError(f"unexpected Matrix revision {revision!r}")
    if git(matrix, "status", "--porcelain", "--", "contract"):
        raise PinError(f"{matrix}/contract has local changes; pin a clean, committed revision")

    publisher(matrix, "--self-test")
    publisher(matrix, "--check", str(VENDORED))
    with tempfile.TemporaryDirectory() as tmp:
        wire = Path(tmp) / "wire"
        export_path = Path(tmp) / "matrix-consumer.json"
        publisher(matrix, "--out", str(wire))
        publisher(matrix, "--verify", str(wire))
        publisher(matrix, "--consumer-out", str(export_path))
        publisher(matrix, "--consumer-check", str(export_path))
        export_bytes = export_path.read_bytes()
        cut_lock = json.loads((wire / "contract.lock").read_bytes().decode("utf-8"))
        vendored_lock = json.loads((VENDORED / "contract.lock").read_bytes().decode("utf-8"))

        if cut_lock["source_commit"] != revision:
            raise PinError(f"cut source {cut_lock['source_commit']} is not HEAD {revision}")
        # The vendored v1.4 copy and the fresh cut: same file list, same bytes.
        if sorted(cut_lock["files"]) != sorted(vendored_lock["files"]):
            raise PinError("the fresh cut and the vendored copy list different files")
        for rel in cut_lock["files"]:
            if (wire / rel).read_bytes() != (VENDORED / rel).read_bytes():
                raise PinError(f"{rel} differs between the fresh cut and the vendored copy")
        for key in ("bundle", "bundle_digest", "contract_version", "files"):
            if cut_lock[key] != vendored_lock[key]:
                raise PinError(f"contract.lock {key} differs from the vendored copy")

    export = json.loads(export_bytes.decode("utf-8"))
    profile = export["profile"]
    wire_contract = profile["wire_contract"]
    if export["profile_digest"] != profile_digest(profile):
        raise PinError("the export's profile_digest does not match its profile")
    if wire_contract["contract_version"] != cut_lock["contract_version"]:
        raise PinError("the export's contract_version differs from the cut")
    if wire_contract["bundle_digest"] != cut_lock["bundle_digest"]:
        raise PinError("the export's bundle_digest differs from the cut")
    if not HEX40.match(wire_contract["verified_source_commit"]):
        raise PinError("the export's verified_source_commit is not a full revision")

    values = {
        "contract_version": wire_contract["contract_version"],
        "bundle_digest": wire_contract["bundle_digest"],
        "verified_source_commit": wire_contract["verified_source_commit"],
        "publisher_revision": revision,
        "publisher_review": review,
        "export_sha256": hashlib.sha256(export_bytes).hexdigest(),
        "profile_digest": export["profile_digest"],
    }
    for key in ("bundle_digest", "export_sha256", "profile_digest"):
        if not HEX64.match(values[key]):
            raise PinError(f"{key} is not 64 lowercase hex")
    return export_bytes, render(values)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    ap.add_argument("--review", help="review status of the publisher revision (--write only)")
    a = ap.parse_args(argv)
    try:
        matrix = matrix_root()
        if a.write:
            if not a.review:
                raise PinError("--write needs --review describing the publisher revision's status")
            export_bytes, pin = build(matrix, a.review)
            EXPORT.parent.mkdir(parents=True, exist_ok=True)
            EXPORT.write_bytes(export_bytes)
            PIN_RS.write_bytes(pin.encode("utf-8"))
            print(f"pinned Matrix publisher {git(matrix, 'rev-parse', 'HEAD')}")
            return 0
        tracked = tracked_values()
        head = git(matrix, "rev-parse", "HEAD")
        if head != tracked["publisher_revision"]:
            raise PinError(
                f"{matrix} is at {head}, not the pinned publisher "
                f"{tracked['publisher_revision']}; check out the pinned revision"
            )
        export_bytes, pin = build(matrix, tracked["publisher_review"])
        bad = []
        if not EXPORT.is_file() or EXPORT.read_bytes() != export_bytes:
            bad.append(str(EXPORT.relative_to(SERVER)))
        if PIN_RS.read_bytes() != pin.encode("utf-8"):
            bad.append(str(PIN_RS.relative_to(SERVER)))
        if bad:
            raise PinError("differs from what the pinned publisher exports: " + ", ".join(bad))
    except (FileNotFoundError, PinError, subprocess.CalledProcessError, KeyError) as error:
        print(f"matrix pin: {error}", file=sys.stderr)
        return 1
    print(f"matrix pin: export and generated constants match publisher {head}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
